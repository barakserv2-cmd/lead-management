-- המספר הווירטואלי שאליו התקשר המועמד — ייחוס ערוץ, בעמודה ולא בהערות.
--
-- הרקע (28.09): מערכת מעקב השיחות מדווחת בכל מייל "מקור: <מספר>", ולכל
-- ערוץ פרסום יש מספר משלו (1099 = האתר, 0145 = גוגל). המידע הזה נשמר עד
-- היום רק בתוך טקסט ההערות, ולכן כל שאלה על ביצועי ערוץ דרשה regex על
-- notes — וגם החזירה תשובה חלקית.
--
-- חלקית, כי כשהרכזת **עונה** לשיחה היא מקלידה את הליד בעצמה; המייל של
-- מסקיו מגיע דקה אחריה, נתפס ככפילות טלפון, **והמספר הווירטואלי נזרק**.
-- כלומר דווקא השיחות שנענו — אלה עם הסיכוי הגבוה ביותר — היו חסרות ייחוס.
alter table leads add column if not exists source_number text;

comment on column leads.source_number is
  'המספר הווירטואלי (מסקיו) שאליו הגיעה השיחה — מזהה את ערוץ הפרסום';

create index if not exists idx_leads_source_number
  on leads (source_number) where source_number is not null;

-- השלמה למפרע ממה שכבר נשמר בהערות, כדי שההשוואה ההיסטורית תישאר שלמה
update leads
set source_number = substring(notes from 'מספר וירטואלי: ([0-9]+)')
where source_number is null
  and notes ~ 'מספר וירטואלי: [0-9]+';
