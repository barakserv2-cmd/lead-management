-- ============================================================
-- 00096: סוד לאימות ה-webhook הנכנס — כשאין חתימה של מטא
--
-- 00095 הניחה שהקליטה תמיד תהיה ישירות ממטא, ולכן האימות היחיד הוא
-- חתימת X-Hub-Signature-256 מול META_APP_SECRET. זה נכון בחיבור ישיר
-- (כמו של גובגט), אבל לא דרך ספק.
--
-- 360dialog מקבלים את ההודעה ממטא, מאמתים אותה אצלם, ושולחים אותה
-- הלאה אלינו מהשרתים שלהם. החתימה של מטא מחושבת על הגוף המקורי מול
-- ה-App Secret של אפליקציית *מטא* — ולכן היא לא מגיעה, וכל בקשה שלהם
-- הייתה נדחית אצלנו ב-401. במקום זה הם מאפשרים לקבוע כותרות משלנו
-- על ה-webhook, וזה האימות היחיד שיש: סוד משותף בכותרת.
--
-- הסוד נפרד מ-webhook_token בכוונה. הטוקן יושב בכתובת ולכן מגיע ללוגים,
-- להיסטוריית דפדפן ולכל proxy בדרך; הסוד יושב בכותרת בלבד. טוקן מנתב,
-- סוד מאמת — שני תפקידים, שני ערכים.
-- ============================================================

ALTER TABLE whatsapp_accounts
  ADD COLUMN IF NOT EXISTS webhook_secret TEXT NOT NULL DEFAULT gen_random_uuid()::text;

COMMENT ON COLUMN whatsapp_accounts.webhook_secret IS
  'סוד משותף לאימות webhook נכנס מספק (Authorization: Bearer). בחיבור ישיר למטא לא בשימוש — שם מאמתים בחתימת X-Hub-Signature-256';
