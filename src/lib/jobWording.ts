/**
 * ניסוחים אסורים בדרישות משרה — חוק שוויון ההזדמנויות בעבודה, התשמ"ח-1988.
 *
 * שלוש משרות פתוחות שידרו למועמדים "בנות יפות", "עדיפות לבנות" ו"עדיפות
 * לרוסים". גובגט הקריא אותן כלשונן, כי הוא אומר מה שכתוב בטבלה. הטקסט תוקן,
 * וכאן נחסמת ההקלדה הבאה.
 *
 * ההבחנה שהבדיקה עושה: **דרישה מקצועית מותרת, שיוך אישי אסור.** "יתרון
 * לדוברי רוסית" חוקי — שפה היא כישור. "עדיפות לרוסים" אינו חוקי — מוצא אינו
 * כישור. אותו צורך עסקי, ניסוח אחר.
 */

interface Rule {
  test: RegExp;
  what: string;
  instead: string;
}

const RULES: Rule[] = [
  {
    // "יפה/יפות/נאה" כתכונה — לא "עדיפות", שמכילה את אותן אותיות
    test: /(?<!עד)(יפה|יפות|יפים|יפיפי)|נאה|נאות\b|חתיך|מראה טוב|חזות/,
    what: "מראה חיצוני",
    instead: "הופעה ייצוגית",
  },
  {
    test: /רק ?(בנות|בחורות|נשים|גברים|בחורים)|עדיפות ל(בנות|בחורות|נשים|גברים|בחורים)|(בנות|בחורות|נשים|גברים) בלבד/,
    what: "מין",
    instead: "לתאר את הדרישה המקצועית עצמה",
  },
  {
    test: /עדיפות ל(רוסים|ערבים|יהודים|אתיופים|צרפתים)|רק (יהודים|ערבים|רוסים)/,
    what: "מוצא או לאום",
    instead: "יתרון לדוברי <שפה>",
  },
  {
    test: /עד גיל|מתחת לגיל|מעל גיל|צעיר(ים|ות)? בלבד|גיל \d{2}[-–]\d{2}/,
    what: "גיל",
    instead: "לתאר את הניסיון הנדרש",
  },
  {
    test: /רווק|נשוי|נשואה|ללא ילדים|לא בהריון|לא בהיריון/,
    what: "מצב משפחתי או הריון",
    instead: "לתאר את הזמינות הנדרשת",
  },
  {
    test: /רק (דתיים|חילונים|שומרי שבת)|עדיפות ל(דתיים|חילונים)/,
    what: "דת",
    instead: "זמינות למשמרות שבת",
  },
];

export interface WordingProblem {
  what: string;
  matched: string;
  instead: string;
}

/** מחזיר את הבעיה הראשונה שנמצאה, או null אם הניסוח תקין. */
export function checkJobWording(text: string): WordingProblem | null {
  const s = (text ?? "").trim();
  if (!s) return null;
  for (const r of RULES) {
    const m = r.test.exec(s);
    if (m) return { what: r.what, matched: m[0], instead: r.instead };
  }
  return null;
}

/** הודעה לרכזת, בעברית, שמסבירה מה להחליף ובמה. */
export function wordingErrorMessage(p: WordingProblem): string {
  return `"${p.matched}" — דרישה לפי ${p.what} אסורה בחוק שוויון ההזדמנויות בעבודה, וגובגט יקריא אותה למועמדים. במקום זה: ${p.instead}.`;
}
