/**
 * ניסוחים אסורים בדרישות משרה — חוק שוויון ההזדמנויות בעבודה, התשמ"ח-1988.
 *
 * סריקה של 239 משרות מצאה חמישה ניסוחים ששודרו למועמדים דרך גובגט:
 * "בנות יפות", "עדיפות לבנות", "עדיפות לרוסים", "2 בנות עדיפות ישראליות"
 * ו"ישראלים!!". גובגט אומר מה שכתוב בטבלה, ולכן הטקסט הזה הגיע לאנשים.
 *
 * ההבחנה שהבדיקה עושה: **דרישה מקצועית מותרת, שיוך אישי אסור.** "יתרון
 * לדוברי רוסית" חוקי — שפה היא כישור. "עדיפות לרוסים" אינו חוקי — מוצא אינו
 * כישור. אותו צורך עסקי, ניסוח אחר.
 *
 * חשוב לא פחות: בדיקה שחוסמת דרישה לגיטימית גורמת לרכזות לעקוף אותה. הגרסה
 * הראשונה חסמה "בונוסים: כולל טיפים", כי "טיפים" מכיל "יפים".
 */

interface Rule {
  test: RegExp;
  what: string;
  instead: string;
}

const RULES: Rule[] = [
  {
    // תכונת מראה. גבול־מילה משמאל חוסם את "טיפים", ו-(?<!עד) את "עדיפות".
    test: /(?<![א-ת])(?<!עד)(יפה|יפות|יפים|יפיפי)|(?<![א-ת])נאה(?![א-ת])|חתיך|מראה טוב|חזות נאה/,
    what: "מראה חיצוני",
    instead: "הופעה ייצוגית",
  },
  {
    // כולל את הצורה ההפוכה שנמצאה בפועל: "2 בנות עדיפות ישראליות"
    test: /רק ?(בנות|בחורות|נשים|גברים|בחורים)|עדיפות ל?(בנות|בחורות|נשים|גברים|בחורים)|(בנות|בחורות|נשים|גברים|אימהות) (בלבד|עדיפות)|\d+ ?(בנות|בחורות|גברים|בחורים)/,
    what: "מין",
    instead: "לתאר את הדרישה המקצועית עצמה",
  },
  {
    // "ישראלים!!" ו"עדיפות ישראליות" הופיעו בלי המבנה "עדיפות ל..."
    test: /עדיפות ל?(רוסים|ערבים|יהודים|אתיופים|צרפתים|ישראלים|ישראליות)|רק (יהודים|ערבים|רוסים|ישראלים)|ישראלים ?!|ישראליות(?![א-ת])/,
    what: "מוצא או לאום",
    instead: "יתרון לדוברי <שפה>, אם זה מה שנדרש בפועל",
  },
  {
    // העסקת נוער היא קטגוריה מוסדרת בחוק — "מתחת לגיל 18" מתאר את המשרה
    // ואינו הדרה, ולכן אינו נחסם. הדרה כלפי מעלה כן.
    test: /עד גיל \d|מעל גיל \d|צעיר(ים|ות)? בלבד|גיל \d{2} ?[-–] ?\d{2}|מבוגר(ים|ות)(?![א-ת])|למבוגרות/,
    what: "גיל",
    instead: "לתאר את הניסיון הנדרש",
  },
  {
    test: /רווק|נשוי|נשואה|ללא ילדים|לא בהריון|לא בהיריון|אימהות(?![א-ת])/,
    what: "מצב משפחתי או הריון",
    instead: "לתאר את שעות המשמרת",
  },
  {
    test: /רק (דתיים|חילונים|שומרי שבת)|עדיפות ל(דתיים|חילונים)/,
    what: "דת",
    instead: "זמינות למשמרות שבת",
  },
];

export interface WordingProblem {
  what: string;
  matched: string;
  instead: string;
}

/** מחזיר את הבעיה הראשונה שנמצאה, או null אם הניסוח תקין. */
export function checkJobWording(text: string): WordingProblem | null {
  const s = (text ?? "").trim();
  if (!s) return null;
  for (const r of RULES) {
    const m = r.test.exec(s);
    if (m) return { what: r.what, matched: m[0], instead: r.instead };
  }
  return null;
}

/** הודעה לרכזת, בעברית, שמסבירה מה להחליף ובמה. */
export function wordingErrorMessage(p: WordingProblem): string {
  return `"${p.matched}" — דרישה לפי ${p.what} אסורה בחוק שוויון ההזדמנויות בעבודה, וגובגט יקריא אותה למועמדים. במקום זה: ${p.instead}.`;
}
