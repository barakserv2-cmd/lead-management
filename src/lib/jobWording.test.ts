import { describe, expect, it } from "vitest";
import { checkJobWording } from "./jobWording";

/**
 * שלוש המשרות שנמצאו בפועל שידרו את הניסוחים האלה למועמדים דרך גובגט.
 * הטסטים נועלים אותם, ובאותה מידה נועלים את מה שמותר — בדיקה שחוסמת
 * דרישה מקצועית לגיטימית תגרום לרכזות לעקוף אותה.
 */
describe("checkJobWording", () => {
  it("חוסם את שלושת הניסוחים שנמצאו במערכת", () => {
    expect(checkJobWording("בנות יפות | מגורים: יש")?.what).toBe("מראה חיצוני");
    expect(checkJobWording("עדיפות לבנות אנגלית צריך")?.what).toBe("מין");
    expect(checkJobWording("עדיפות לרוסים")?.what).toBe("מוצא או לאום");
  });

  it("חוסם גיל, מצב משפחתי ודת", () => {
    expect(checkJobWording("עד גיל 30")?.what).toBe("גיל");
    expect(checkJobWording("רווק ללא ילדים")?.what).toBe("מצב משפחתי או הריון");
    expect(checkJobWording("רק שומרי שבת")?.what).toBe("דת");
  });

  it("מאפשר דרישות מקצועיות — כולל אלה שדומות למילים החסומות", () => {
    for (const ok of [
      "יתרון לדוברי רוסית",
      "אנגלית ברמה טובה — נדרש לשיחה מול אורחים",
      "הופעה ייצוגית · יחסי אנוש טובים | מגורים: יש",
      "שירות צבאי מלא חובה",
      "עדיפות לבעלי ניסיון קודם",
      "זמינות למשמרות שבת",
      "ניסיון של שנתיים לפחות",
      "תעודת חשמלאי חובה",
    ]) {
      expect(checkJobWording(ok), ok).toBeNull();
    }
  });

  it("טקסט ריק אינו בעיה", () => {
    expect(checkJobWording("")).toBeNull();
    expect(checkJobWording("   ")).toBeNull();
  });
});

/**
 * הגרסה הראשונה חסמה "בונוסים: כולל טיפים", כי "טיפים" מכיל "יפים" —
 * וסקירה ידנית של 239 משרות מצאה שלושה ניסוחים שהיא פספסה לגמרי.
 */
describe("מה שנמצא בסריקה של כל המשרות", () => {
  it("חוסם את הצורות שהבדיקה הראשונה פספסה", () => {
    expect(checkJobWording("בונוסים: 2 בנות עדיפות ישראליות")).not.toBeNull();
    expect(checkJobWording("בונוסים: ישראלים!!")?.what).toBe("מוצא או לאום");
    expect(checkJobWording("עבודה בוקר 10-18 (עדיפות למבוגרות/אימהות)")).not.toBeNull();
    expect(checkJobWording("בונוסים: עדיפות לרוסים מבוגרים")?.what).toBe("מוצא או לאום");
  });

  it("לא חוסם טיפים — זו הטעות שהייתה", () => {
    for (const ok of [
      "בונוסים: כולל טיפים",
      "בונוסים: טיפים גבוהים | מגורים: יש",
      "בונוסים: יכול להיות עם טיפים | מגורים: יש",
      "בונוסים: מתאים למועדפת-טיפים | מגורים: יש",
    ]) {
      expect(checkJobWording(ok), ok).toBeNull();
    }
  });

  it("העסקת נוער היא קטגוריה חוקית ולא נחסמת", () => {
    expect(checkJobWording("מתחת לגיל 18 כולל שבת")).toBeNull();
  });

  it("ממשיך לאפשר את שאר הדרישות האמיתיות שבמערכת", () => {
    for (const ok of [
      "בונוסים: תעודת מציל+עזרה ראשונה חובה | מגורים: יש",
      "בונוסים: שירות צבאי מלא-איכותים | מגורים: יש | יכולות חימוש",
      "מגורים: יש | רישיון חובה",
      "בונוסים: ניסיון מלונאי חלבי | מגורים: יש",
      "שישי לסירוגין מענק התמדה 3K ב4 פעימות 8-19 בונוסים גבוהים חייב אנגלית ושליטה במחשב",
    ]) {
      expect(checkJobWording(ok), ok).toBeNull();
    }
  });
});
