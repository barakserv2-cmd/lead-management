def checks(items, cls="checks"):
    return f'<ul class="{cls}">' + "".join(f"<li>{C}<span>{t}</span></li>" for t in items) + "</ul>"


def card(icon, title, text, extra=""):
    return f'<article class="card"><div class="icon">{ICON[icon]}</div><h3>{title}</h3><p>{text}</p>{extra}</article>'


def faq(items):
    return '<div class="faq">' + "".join(
        f'<details><summary>{q}</summary><div class="a">{a}</div></details>' for q, a in items) + "</div>"


def write(name, html):
    with open(os.path.join(OUT, name), "w", encoding="utf-8") as f:
        f.write(html)


